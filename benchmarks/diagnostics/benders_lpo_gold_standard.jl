"""How much cut strength does the CONSERVATIVE inactive completion (`rho <= 0`) give up?

The production method never enumerates the full route family `R`. On a tiny instance we can,
and then the true Magnanti-Wong dual -- optimal face, core-point objective, and the REAL route
rows for every column in `R`, with no `rho <= 0` condition anywhere -- is computable. That is
the gold standard the conservative completion is an approximation to, and the gap between them
is the price of not being able to write `R` down.

Four arms at the same anchors, in increasing order of what they are allowed to know:

    closed_form   `_benders_activated_complete_duals!` -- the incumbent practice
    baseline      Method A: alpha_hat and built gamma_hat FIXED, `J0` multipliers chosen to
                  minimise their damage at the core point subject to `rho <= 0`
    pareto        Method B: the whole dual re-optimised over the optimal face, same
                  `rho <= 0` rows, route rows generated by re-pricing to certification
    gold          the same optimal-face core-point objective, but with the real route rows
                  for EVERY column of the enumerated `R` and NO `rho <= 0` rows

`gold` is a valid cut by the plain dual-feasibility argument (its rows ARE the full dual's
rows), so it upper-bounds what any completion-based method can reach, and
`gold - pareto` is exactly the conservatism of the `rho <= 0` rule.

**Testing only.** `gold` enumerates `R`; the production algorithm must never depend on that,
which is the entire reason the other three arms exist.

Usage: sbatch --array=1-4 benchmarks/diagnostics/run_benders_lpo_gold_standard.sh
Env: GS_N GS_P GS_S GS_SEED GS_MAX_STOPS GS_ANCHORS
"""

using StationSelection
using JuMP
# The gold arm builds its own LP, so it needs the optimizer directly -- every other script
# here only ever goes through `run_opt`/`build_model` and gets it from inside the package.
using Gurobi
using Printf
using Combinatorics
include(joinpath(@__DIR__, "..", "lib", "cg_benchmark.jl"))

const N = parse(Int, get(ENV, "GS_N", "8"))
const P = parse(Int, get(ENV, "GS_P", "6"))
const S = parse(Int, get(ENV, "GS_S", "1"))
const SEED = parse(Int, get(ENV, "GS_SEED", "42"))
const MAX_STOPS = parse(Int, get(ENV, "GS_MAX_STOPS", "3"))
const N_ANCHORS = parse(Int, get(ENV, "GS_ANCHORS", "6"))
const TOL = 1e-6

problem, k, _meta = benchmark_problem(@__DIR__, "GS", N, P, S, SEED)
data = problem.data
formulation = AggregateODRouteJointRoutingAssignmentFormulation(
    ; BENCHMARK_BASELINE..., max_stops = MAX_STOPS)

make_solver(oracle, completion) = BendersSolver(
    config = SolverOptions(silent = true), max_iterations = 500,
    subproblem = BendersSubproblemConfig(
        oracle = oracle, max_stops = MAX_STOPS, max_routes = 500_000,
        enumeration_time_limit_sec = 600.0, lpo_completion = completion))

enum_solver = make_solver(:direct_enumeration, :pareto)
enum_build = build_model(problem, formulation, enum_solver)
enum_master = enum_build.model
mapping = enum_build.mapping
enum_subs = enum_master[:benders_subproblem_builds]
pool = [collect(values(b.model[:joint_routing_assignment_columns])) for b in enum_subs]
walk_cost_weight = Float64(enum_subs[1].model[:joint_routing_assignment_walk_cost_weight])
@printf("instance: zhuzhou n=%d p=%d s=%d seed=%d k=%d max_stops=%d | pool %s\n",
        N, P, S, SEED, k, MAX_STOPS, join(length.(pool), "+"))

core_point, core_slack = StationSelection._benders_core_point(data, mapping, k)
@printf("core point: min slack %.4f\n", core_slack)

# ---- the master's feasible set and the exact value function -------------------------
required = Set{Int}()
for s in 1:n_scenarios(data)
    for (p, (o, d)) in enumerate(mapping.Omega_s[s])
        mapping.Q_s[s][p] > 0 || continue
        any(is_walk_only_pair, get_valid_jk_pairs(mapping, o, d)) && continue
        push!(required, o); push!(required, d)
    end
end
candidates = Dict(pt => Set(j for j in 1:N
                            if get_walking_cost(data, pt, j) <= mapping.max_walking_distance)
                  for pt in required)
combos = filter(collect(combinations(1:N, k))) do combo
    all(!isempty(intersect(candidates[pt], combo)) for pt in required)
end
isempty(combos) && error("no endpoint-feasible station set at k=$k")
as_y(combo) = (y = zeros(Float64, N); y[combo] .= 1.0; y)
combo_index = Dict(Tuple(sort(c)) => i for (i, c) in enumerate(combos))

Q = Matrix{Float64}(undef, length(combos), n_scenarios(data))
totals = Vector{Float64}(undef, length(combos))
for (i, combo) in enumerate(combos)
    sub = StationSelection._solve_joint_routing_assignment_benders_subproblems(
        enum_master, as_y(combo), enum_solver)
    for r in sub.scenarios; Q[i, r.scenario] = r.objective; end
    totals[i] = sub.total_objective
end
order = sortperm(totals)
picks = unique(vcat(1, [1 + round(Int, (length(order) - 1) * t / max(1, N_ANCHORS - 1))
                        for t in 0:(N_ANCHORS - 1)]))
anchors = order[picks[1:min(end, N_ANCHORS)]]
@printf("value function: %d of %d sets | anchors %d\n",
        length(combos), binomial(N, k), length(anchors))
flush(stdout)

"""The full Magnanti-Wong dual: optimal face, core-point objective, and the REAL route rows
for every column of the enumerated `R`. No `rho <= 0` anywhere -- this is the dual of the
actual second stage, so any feasible point of it gives a valid cut and its optimum bounds
every completion-based method from above."""
function gold_dual(s::Int, incumbent::Vector{Float64}, z_star::Float64)
    sm = enum_subs[s].model
    group_keys, pairs_of, walk_bound = Tuple{Int, Int}[], Dict{Tuple{Int,Int}, Vector{Tuple{Int,Int}}}(), Dict{Tuple{Int,Int}, Float64}()
    pk, dk = Tuple{Tuple{Int,Int}, Int}[], Tuple{Tuple{Int,Int}, Int}[]
    for (p, (o, d)) in enumerate(mapping.Omega_s[s])
        demand = mapping.Q_s[s][p]
        demand > 0 || continue
        key2 = (s, p); push!(group_keys, key2)
        ps, so, sd = Tuple{Int,Int}[], Set{Int}(), Set{Int}()
        for pair in get_valid_jk_pairs(mapping, o, d)
            if is_walk_only_pair(pair)
                walk_bound[key2] = walk_cost_weight * demand *
                    od_pair_walking_cost(data, o, d, WALK_ONLY_PAIR)
                continue
            end
            j, kk = pair; push!(ps, (j, kk))
            j in so || (push!(so, j); push!(pk, (key2, j)))
            kk in sd || (push!(sd, kk); push!(dk, (key2, kk)))
        end
        pairs_of[key2] = ps
    end

    lp = Model(() -> Gurobi.Optimizer()); set_silent(lp)
    @variable(lp, a[key in group_keys] >= 0)
    @variable(lp, go[key in pk] >= 0)
    @variable(lp, gd[key in dk] >= 0)
    @objective(lp, Max,
        sum(a[key] for key in group_keys; init = 0.0) -
        sum(core_point[key[2]] * go[key] for key in pk; init = 0.0) -
        sum(core_point[key[2]] * gd[key] for key in dk; init = 0.0))
    @constraint(lp,
        sum(a[key] for key in group_keys; init = 0.0) -
        sum(go[key] for key in pk if incumbent[key[2]] > 0.5; init = 0.0) -
        sum(gd[key] for key in dk if incumbent[key[2]] > 0.5; init = 0.0) == z_star)
    for (key, bound) in walk_bound
        @constraint(lp, a[key] <= bound)
    end
    for column in pool[s]
        row = AffExpr(0.0)
        for (p, j, kk) in column.assignments
            key2 = (s, p)
            add_to_expression!(row, 1.0, a[key2])
            add_to_expression!(row, -1.0, go[(key2, j)])
            add_to_expression!(row, -1.0, gd[(key2, kk)])
        end
        @constraint(lp, row <= joint_routing_assignment_column_cost(sm, data, mapping, column))
    end
    optimize!(lp)
    termination_status(lp) == MOI.OPTIMAL || return nothing
    alpha = Dict(key => max(0.0, value(a[key])) for key in group_keys)
    gamma_o = Dict(key => max(0.0, value(go[key])) for key in pk)
    gamma_d = Dict(key => max(0.0, value(gd[key])) for key in dk)
    return alpha, gamma_o, gamma_d
end

gamma_by_station(go, gd) = begin
    c = Dict{Int, Float64}()
    for gs in (go, gd), (key, v) in gs
        v == 0.0 && continue
        c[key[2]] = get(c, key[2], 0.0) + v
    end
    c
end

function score(s::Int, anchor_i::Int, alpha, gamma_o, gamma_d)
    coefficients = gamma_by_station(gamma_o, gamma_d)
    constant = sum(values(alpha); init = 0.0)
    core = constant - sum(core_point[j] * get(coefficients, j, 0.0) for j in 1:N; init = 0.0)
    worst_violation, min_rc = -Inf, Inf
    for (i, combo) in enumerate(combos)
        predicted = constant - sum(get(coefficients, j, 0.0) for j in combo; init = 0.0)
        worst_violation = max(worst_violation, predicted - Q[i, s])
    end
    for column in pool[s]
        rc = joint_routing_assignment_column_cost(enum_subs[s].model, data, mapping, column)
        for (p, j, kk) in column.assignments
            key2 = (s, p)
            rc -= get(alpha, key2, 0.0)
            rc += get(gamma_o, (key2, j), 0.0) + get(gamma_d, (key2, kk), 0.0)
        end
        min_rc = min(min_rc, rc)
    end
    built = combos[anchor_i]
    gaps = Float64[]
    for a in built, b in 1:N
        b in built && continue
        idx = get(combo_index, Tuple(sort(vcat(setdiff(built, [a]), b))), nothing)
        isnothing(idx) && continue
        predicted = constant - sum(get(coefficients, j, 0.0) for j in combos[idx]; init = 0.0)
        push!(gaps, Q[idx, s] - predicted)
    end
    inactive = [get(coefficients, j, 0.0) for j in 1:N if !(j in built)]
    mean_of(v) = isempty(v) ? NaN : sum(v) / length(v)
    return (core = core, violation = worst_violation, min_rc = min_rc,
            swap_mean = mean_of(gaps), swap_max = isempty(gaps) ? NaN : maximum(gaps),
            swap_min = isempty(gaps) ? NaN : minimum(gaps),
            g_inactive = mean_of(inactive),
            g_inactive_max = isempty(inactive) ? NaN : maximum(inactive))
end

const ARMS = (:closed_form, :baseline, :pareto, :gold)
results = Dict{Symbol, Vector{NamedTuple}}(arm => NamedTuple[] for arm in ARMS)

for arm in ARMS
    oracle = arm === :closed_form ? :column_generation_activated : :column_generation_activated_lpo
    completion = arm === :baseline ? :baseline : :pareto
    solver = make_solver(arm === :gold ? :column_generation_activated : oracle, completion)
    build = build_model(problem, formulation, solver)
    master = build.model
    subs = master[:benders_subproblem_builds]
    for anchor_i in anchors
        y = as_y(combos[anchor_i])
        sub = StationSelection._solve_joint_routing_assignment_benders_subproblems(
            master, y, solver)
        by_scenario = Dict(r.scenario => r for r in sub.scenarios)
        for s in 1:n_scenarios(data)
            sm = subs[s].model
            z_star = by_scenario[s].objective
            point = if arm === :gold
                gold_dual(s, y, z_star)
            else
                alpha, gamma_o, gamma_d = extract_joint_routing_assignment_duals(sm)
                StationSelection._benders_activated_complete_duals!(
                    alpha, gamma_o, gamma_d, y, data, mapping, s, walk_cost_weight)
                if arm !== :closed_form
                    StationSelection._benders_lpo_completion!(
                        alpha, gamma_o, gamma_d, y, data, mapping, s, subs[s],
                        solver.subproblem, core_point, z_star)
                end
                (alpha, gamma_o, gamma_d)
            end
            isnothing(point) && (@printf("  %s anchor %d s=%d: gold LP not optimal\n",
                                         arm, anchor_i, s); continue)
            push!(results[arm], merge((anchor = anchor_i, scenario = s, z = z_star),
                                      score(s, anchor_i, point...)))
        end
    end
    @printf("arm %-12s done (%d points)\n", arm, length(results[arm]))
    flush(stdout)
end

mean_of(v) = isempty(v) ? NaN : sum(v) / length(v)
println("\n", "="^100)
println("gold standard: how much the conservative `rho <= 0` completion gives up")
println("="^100)
@printf("%-14s %12s %12s %12s %12s %12s %12s\n", "arm", "C(y^c)", "mean swap gap",
        "max swap gap", "mean g_J0", "max g_J0", "min rc")
for arm in ARMS
    r = results[arm]
    isempty(r) && continue
    @printf("%-14s %12.3f %12.3f %12.3f %12.3f %12.3f %+12.2e\n", arm,
            mean_of([x.core for x in r]), mean_of([x.swap_mean for x in r]),
            mean_of([x.swap_max for x in r]), mean_of([x.g_inactive for x in r]),
            mean_of([x.g_inactive_max for x in r]), minimum(x.min_rc for x in r))
end

gold_core = mean_of([x.core for x in results[:gold]])
par_core = mean_of([x.core for x in results[:pareto]])
base_core = mean_of([x.core for x in results[:baseline]])
@printf("\nconservatism of `rho <= 0`:  gold - pareto = %.4f  (%.1f%% of gold - closed_form)\n",
        gold_core - par_core,
        100 * (gold_core - par_core) /
            max(1e-12, gold_core - mean_of([x.core for x in results[:closed_form]])))
@printf("Pareto step itself:          pareto - baseline = %.4f\n", par_core - base_core)

println("\n=== checks ===")
checks = Tuple{String, Bool, String}[]
for arm in ARMS
    r = results[arm]
    isempty(r) && continue
    push!(checks, ("$arm: dual feasible over enumerated R",
                   minimum(x.min_rc for x in r) >= -1e-6,
                   @sprintf("min rc %+.3e", minimum(x.min_rc for x in r))))
    push!(checks, ("$arm: cut valid at every feasible y",
                   maximum(x.violation for x in r) <= TOL,
                   @sprintf("worst violation %+.3e", maximum(x.violation for x in r))))
end
push!(checks, ("gold >= pareto at the core point", gold_core >= par_core - 1e-4,
               @sprintf("%.4f vs %.4f", gold_core, par_core)))
push!(checks, ("pareto >= baseline at the core point", par_core >= base_core - 1e-4,
               @sprintf("%.4f vs %.4f", par_core, base_core)))
for (name, ok, detail) in checks
    @printf("%-58s %s   %s\n", name, ok ? "PASS" : "FAIL", detail)
end
n_fail = count(c -> !c[2], checks)
@printf("\n%d checks, %d failed\n", length(checks), n_fail)
n_fail == 0 || error("verification failed")
println("ALL CHECKS PASSED")
