"""Aggregate and certify Study 1 results.

Usage: `julia --project=. analyze.jl RAW_DIR [RESULTS_DIR]`
All 110 configured jobs must be present and LP/IP optimal before summaries are emitted.
"""

using CSV
using DataFrames
using Dates
using Statistics

1 <= length(ARGS) <= 2 || error("usage: analyze.jl RAW_DIR [RESULTS_DIR]")
raw_dir = abspath(ARGS[1])
project_root = normpath(joinpath(@__DIR__, "..", ".."))
results_dir = length(ARGS) == 2 ? abspath(ARGS[2]) :
    joinpath(project_root, "benchmarks", "results", "$(Dates.today())_study1_formulation_lp_ip_gap")
comparison_names = ("formulation", "max_stops", "max_wait_time", "detour_factor")
jobs_files = [joinpath(@__DIR__, "config", "$(name)_jobs.tsv") for name in comparison_names]

files = sort(filter(path -> endswith(path, ".csv"), readdir(raw_dir; join=true)))
isempty(files) && error("no CSV result files found in $raw_dir")
case_results = reduce(vcat, (CSV.read(path, DataFrame) for path in files))
jobs = reduce(vcat, (CSV.read(path, DataFrame; delim='\t') for path in jobs_files))

duplicate_ids = combine(groupby(case_results, :job_id), nrow => :n)
duplicate_ids = duplicate_ids[duplicate_ids.n .!= 1, :]
isempty(duplicate_ids) || error("duplicate result job IDs: $(join(duplicate_ids.job_id, ", "))")
missing_ids = setdiff(jobs.job_id, case_results.job_id)
extra_ids = setdiff(case_results.job_id, jobs.job_id)
isempty(missing_ids) || error("missing result jobs: $(join(missing_ids, ", "))")
isempty(extra_ids) || error("unexpected result jobs: $(join(extra_ids, ", "))")

bad_sizes = case_results[
    case_results.n_pairs_actual .!= case_results.n_pairs .* case_results.n_scenarios,
    [:job_id, :instance_id, :n_pairs, :n_scenarios, :n_pairs_actual, :pairs_per_scenario],
]
isempty(bad_sizes) || error("generated workload differs from configuration:\n$(sprint(show, bad_sizes))")

bad = case_results[
    (case_results.lp_termination_status .!= "OPTIMAL") .|
    (case_results.ip_termination_status .!= "OPTIMAL") .|
    .!case_results.cg_converged .|
    .!case_results.cg_pricing_exhausted .|
    ismissing.(case_results.z_lp) .|
    ismissing.(case_results.z_ip),
    [:job_id, :instance_id, :comparison, :variant, :lp_termination_status,
        :ip_termination_status, :cg_converged, :cg_pricing_exhausted],
]
isempty(bad) || error("Study 1 is incomplete or uncertified; failing jobs:\n$(sprint(show, bad))")

mkpath(results_dir)
sort!(case_results, [:comparison, :variant, :instance_id])
CSV.write(joinpath(results_dir, "case_results.csv"), case_results)

for comparison in comparison_names
    sub = case_results[case_results.comparison .== comparison, :]
    CSV.write(joinpath(results_dir, "comparison_$(comparison).csv"), sub)
end

summary = combine(groupby(case_results, [:comparison, :variant, :formulation,
        :max_stops, :max_wait_time, :detour_factor]),
    nrow => :n_cases,
    :gap => mean => :mean_gap,
    :gap => median => :median_gap,
    :gap => maximum => :max_gap,
    :z_lp => mean => :mean_z_lp,
    :z_ip => mean => :mean_z_ip,
    :runtime_sec => mean => :mean_runtime_sec,
    :runtime_sec => median => :median_runtime_sec,
    :cg_iterations => mean => :mean_cg_iterations,
    :n_columns => mean => :mean_n_columns,
)
sort!(summary, [:comparison, :variant])
CSV.write(joinpath(results_dir, "variant_summary.csv"), summary)

open(joinpath(results_dir, "slides_results.tex"), "w") do io
    println(io, "% Generated by Study 1 analyze.jl; all rows passed LP/IP certification")
    for (i, row) in enumerate(eachrow(summary))
        println(io, "\\newcommand{\\StudyOneRow$(i)}{$(row.comparison) & $(row.variant) & " *
            "$(round(row.mean_gap; digits=4)) & $(round(row.mean_runtime_sec; digits=2))}")
    end
end

println("Certified all $(nrow(case_results)) jobs; wrote four comparisons to $results_dir")
